/*aula01.js — O Primeiro Contato e Variáveis
Conceito: O que é o Node, como imprimir na tela (console.log) e como guardar informações em caixas (let e const).

Exemplo Humano: Imagine que você está em um laboratório de química. 
Você precisa etiquetar os frascos. 
O let é um frasco que você pode esvaziar e encher com outra coisa depois. 
O const é um frasco lacrado que, uma vez cheio, não pode ser alterado.*/


// aula01.js
console.log("Iniciando o laboratório de código...");

// let: pode mudar o valor (variável)
let temperatura = 25;
temperatura = 30; // O frasco mudou de conteúdo

// const: valor constante (não pode mudar)
const PI = 3.14159; 

console.log(`A temperatura atual é ${temperatura} graus e o PI é ${PI}.`);

export{} /*Me ajudou a remover alguns erros*/
  
